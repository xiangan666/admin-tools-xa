// Row-format presets for scoreboard holograms. Selecting one sets cfg.rowFormat;
// "Custom" opens a text field that accepts & color codes. Text is left
// uncolored so it stays legible on both the dark hologram and the light picker
// button; only the score is accented (§2) and closed with §r to stop bleed.
const ROW_PRESETS = [
  { fmt: "{rank}. {name} - §2{score}§r" },
  { fmt: "{name}: §2{score}§r" },
  { fmt: "#{rank} {name} §2{score}§r" },
  { fmt: "{name} (§2{score}§r)" },
  { fmt: "§2{score}§r - {name}" },
];

// Time-readout modes for objectives whose score counts MINUTES (the Playtime
// stat leaderboard). "" leaves the score as a plain number. The picker labels
// are generated by the renderer itself so what you choose is exactly what the
// hologram shows — same WYSIWYG approach as the row-format samples above.
const TIME_FORMATS = ["", "h", "hm", "m"];
const TIME_SAMPLE_MINUTES = 2535; // 42h 15m — exercises all three modes

/** A fresh scoreboard config with sensible defaults. */
function defaultScoreboardCfg() {
  return {
    objective: "",
    title: "",
    topN: 10,
    rowFormat: "",
    sort: "desc",
    hideOffline: false,
    commaScores: false,
    timeFormat: "",
  };
}

