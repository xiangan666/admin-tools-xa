/**
 * DDUI (CustomForm) hub for scoreboard holograms, used for create and edit.
 * Everything is inline and reactive: the preview re-renders on every change AND
 * on a ~10s interval (so changing live scores show), cleaned up when the form
 * closes. ctx = { mode, entity?, blockLocation?, cfg, pos }.
 * spawnHologram/updateHologram stay the authority.
 */
async function showScoreboardHub(player, ctx) {
  const cfg = ctx.cfg;
  let objectives = [];
  try {
    objectives = world.scoreboard.getObjectives();
  } catch {}
  // Hide the addon's internal kit bookkeeping objectives (cooldown jm_at_k<id>
  // and claim-count jm_at_kc<id>) — they're not leaderboards anyone would show.
  objectives = objectives.filter((o) => !String(o.id).startsWith(`${NS}_k`));
  const hasObjs = objectives.length > 0;

  // Objective: pick an existing one, or create a new one inline.
  const objItems = objectives.map((o, i) => ({
    label: `${String(o.displayName || o.id).replace(/§./g, "")} (${o.id})`,
    value: i,
  }));
  const curObjIdx = objectives.findIndex((o) => o.id === cfg.objective);
  const objIdx = new ObservableNumber(curObjIdx < 0 ? 0 : curObjIdx, {
    clientWritable: true,
  });
  const createNew = new ObservableBoolean(!hasObjs, { clientWritable: true });
  const pickShown = new ObservableBoolean(hasObjs && !createNew.getData());
  createNew.subscribe((v) => pickShown.setData(hasObjs && !v));
  const newObjId = new ObservableString("", { clientWritable: true });
  const newObjName = new ObservableString("", { clientWritable: true });

  // Display options.
  const titleObs = new ObservableString(toAmpCodes(cfg.title ?? ""), {
    clientWritable: true,
  });
  const topNObs = new ObservableNumber(cfg.topN ?? 10, {
    clientWritable: true,
  });

  const presetSample = (fmt) =>
    fmt
      .replace(/\{rank\}/g, "1")
      .replace(/\{name\}/g, "Steve")
      .replace(/\{score\}/g, "50")
      .replace(/§./g, "");
  const customValue = ROW_PRESETS.length;
  const fmtItems = ROW_PRESETS.map((p, i) => ({
    label: presetSample(p.fmt),
    value: i,
  }));
  fmtItems.push({ label: t("jm_at.holo.option_custom"), value: customValue });
  const presetMatch = ROW_PRESETS.findIndex((p) => p.fmt === cfg.rowFormat);
  const startCustom = presetMatch < 0 && (cfg.rowFormat ?? "").length > 0;
  const fmtIdx = new ObservableNumber(
    startCustom ? customValue : presetMatch < 0 ? 0 : presetMatch,
    { clientWritable: true },
  );
  const customFmt = new ObservableString(
    startCustom ? toAmpCodes(cfg.rowFormat) : "",
    { clientWritable: true },
  );
  const customShown = new ObservableBoolean(startCustom);
  fmtIdx.subscribe((v) => customShown.setData(v === customValue));

  // Time readout. Only meaningful for objectives that count minutes, so it
  // defaults to "plain number" for everything else and is harmless if left
  // alone. Playtime leaderboards arrive from the stat picker pre-set to hours.
  const tfItems = TIME_FORMATS.map((mode, i) => ({
    label: mode
      ? formatTimeScore(TIME_SAMPLE_MINUTES, mode)
      : t("jm_at.holo.time_fmt_plain"),
    value: i,
  }));
  const tfIdx = new ObservableNumber(
    Math.max(0, TIME_FORMATS.indexOf(cfg.timeFormat ?? "")),
    { clientWritable: true },
  );

  const sortDesc = new ObservableBoolean((cfg.sort ?? "desc") !== "asc", {
    clientWritable: true,
  });
  const hideOffline = new ObservableBoolean(!!cfg.hideOffline, {
    clientWritable: true,
  });
  const commaScores = new ObservableBoolean(!!cfg.commaScores, {
    clientWritable: true,
  });

  // Position.
  const xObs = new ObservableString(String(ctx.pos.x), {
    clientWritable: true,
  });
  const yObs = new ObservableString(String(ctx.pos.y), {
    clientWritable: true,
  });
  const zObs = new ObservableString(String(ctx.pos.z), {
    clientWritable: true,
  });

  const preview = new ObservableString("");
  const status = new ObservableString("");
  const statusShown = new ObservableBoolean(false);

  const resolveObjId = () =>
    createNew.getData()
      ? newObjId.getData().trim().replace(/\s+/g, "_")
      : (objectives[objIdx.getData()]?.id ?? "");

  const buildCfg = () => ({
    objective: resolveObjId(),
    title: applyColorCodes(titleObs.getData().trim()),
    topN: Math.min(
      Math.max(1, Math.round(topNObs.getData())),
      LIMITS.HOLOGRAM_LINE_MAX,
    ),
    rowFormat:
      fmtIdx.getData() === customValue
        ? applyColorCodes(customFmt.getData().trim())
        : (ROW_PRESETS[fmtIdx.getData()]?.fmt ?? ""),
    sort: sortDesc.getData() ? "desc" : "asc",
    hideOffline: hideOffline.getData(),
    commaScores: commaScores.getData(),
    timeFormat: TIME_FORMATS[tfIdx.getData()] ?? "",
  });

  const refreshPreview = () => {
    const c = buildCfg();
    if (!c.objective) {
      preview.setData("§7请选择计分项目或输入名称以预览。");
      return;
    }
    try {
      const lines = renderScoreboardLines(c);
      preview.setData(
        lines.length
          ? lines.map((l) => l + "§r").join("\n")
          : "§7（尚无条目）",
      );
    } catch {
      preview.setData("§7（无法预览）");
    }
  };
  const onEdit = () => {
    refreshPreview();
    status.setData("");
    statusShown.setData(false);
  };
  refreshPreview();
  for (const o of [
    objIdx,
    createNew,
    newObjId,
    titleObs,
    topNObs,
    fmtIdx,
    customFmt,
    tfIdx,
    sortDesc,
    hideOffline,
    commaScores,
  ]) {
    o.subscribe(onEdit);
  }

  // Dirty-check: closing with unsaved edits prompts before discarding.
  const snapshot = () =>
    JSON.stringify([
      buildCfg(),
      xObs.getData(),
      yObs.getData(),
      zObs.getData(),
    ]);
  const initial = snapshot();
  let pendingNav = null;
  let saved = false; // commit succeeded → skip the discard prompt on close

  const form = new CustomForm(
    player,
    ctx.mode === "edit"
      ? t("jm_at.holo.sb_edit_title")
      : t("jm_at.holo.sb_create_title"),
  );
  form.header(t("jm_at.holo.header_live_preview"));
  form.spacer();
  form.label(preview);
  form.spacer();
  form.label(t("jm_at.holo.label_refresh_note"));
  form.spacer();

  if (hasObjs) {
    form.dropdown(t("jm_at.holo.field_objective"), objIdx, objItems, {
      visible: pickShown,
    });
    form.toggle(t("jm_at.holo.toggle_create_new"), createNew);
  }
  form.textField(t("jm_at.holo.field_new_obj_id"), newObjId, {
    visible: createNew,
    description: t("jm_at.holo.field_new_obj_id_desc"),
  });
  form.textField(t("jm_at.holo.field_new_obj_name"), newObjName, {
    visible: createNew,
    description: t("jm_at.holo.field_new_obj_name_desc"),
  });

  form.textField(t("jm_at.holo.field_title"), titleObs, {
    description: t("jm_at.holo.field_title_desc"),
  });
  form.slider(
    t("jm_at.holo.field_rows_shown"),
    topNObs,
    1,
    LIMITS.HOLOGRAM_LINE_MAX,
    { step: 1 },
  );
  form.dropdown(t("jm_at.holo.field_row_format"), fmtIdx, fmtItems);
  form.textField(t("jm_at.holo.field_custom_format"), customFmt, {
    visible: customShown,
    description: t("jm_at.holo.field_custom_format_desc"),
  });
  form.dropdown(t("jm_at.holo.field_time_format"), tfIdx, tfItems);
  form.toggle(t("jm_at.holo.toggle_sort_desc"), sortDesc);
  form.toggle(t("jm_at.holo.toggle_hide_offline"), hideOffline);
  form.toggle(t("jm_at.holo.toggle_comma_scores"), commaScores);

  form.spacer();
  form.label(t("jm_at.holo.label_position"));
  form.spacer();
  form.textField(t("jm_at.holo.field_x"), xObs);
  form.textField(t("jm_at.holo.field_y"), yObs);
  form.textField(t("jm_at.holo.field_z"), zObs);
  form.spacer();
  form.label(status, { visible: statusShown });
  form.spacer({ visible: statusShown });

  const fail = (msg) => {
    status.setData(msg);
    statusShown.setData(true);
  };

  const commit = () => {
    const c = buildCfg();
    if (createNew.getData()) {
      if (!c.objective) return fail("§c请输入新计分项目的ID。");
      try {
        let obj = world.scoreboard.getObjective(c.objective);
        if (!obj) {
          obj = world.scoreboard.addObjective(
            c.objective,
            newObjName.getData().trim() || c.objective,
          );
        }
      } catch {
        return fail(
          "§c无法创建计分项目，ID可能无效或已被占用。",
        );
      }
    } else if (!c.objective) {
      return fail("§c请先选择计分项目。");
    }
    // Blank title → use the objective's display name (matches old behavior).
    if (!c.title) {
      try {
        const o = world.scoreboard.getObjective(c.objective);
        c.title = o ? o.displayName || o.id : c.objective;
      } catch {
        c.title = c.objective;
      }
    }
    const x = parseFloat(xObs.getData());
    const y = parseFloat(yObs.getData());
    const z = parseFloat(zObs.getData());
    if (isNaN(x) || isNaN(y) || isNaN(z)) {
      return fail("§c坐标无效，请只输入数字。");
    }
    const pos = { x, y, z };

    let lines;
    try {
      lines = renderScoreboardLines(c);
    } catch {
      lines = [];
    }

    if (ctx.mode === "edit") {
      updateHologram(ctx.entity, lines, pos, c);
      tell(player, t("jm_at.holo.sb_updated"));
    } else {
      if (getHologramRegistry().length >= LIMITS.HOLOGRAM_REGISTRY_MAX) {
        return fail(
          `§c全息图数量已达上限（${LIMITS.HOLOGRAM_REGISTRY_MAX}），请先删除一个。`,
        );
      }
      const placed = spawnHologram(player, lines, pos, c);
      if (!placed) {
        return fail(
          "§c无法保存全息图：存储空间已满。请删除全息图或其他数据后重试。",
        );
      }
      tell(player, t("jm_at.holo.sb_placed"));
    }
    saved = true;
    try {
      form.close();
    } catch {}
  };

  form.button(
    ctx.mode === "edit"
      ? t("jm_at.holo.btn_save_changes")
      : t("jm_at.holo.btn_place"),
    commit,
  );
  if (ctx.mode === "edit") {
    form.button(t("jm_at.holo.btn_remove"), () => {
      pendingNav = () => showRemoveConfirm(player, ctx.entity);
      try {
        form.close();
      } catch {}
    });
  }
  // Live refresh while the form is open (~10s), cleaned up on close.
  const intervalId = system.runInterval(refreshPreview, 200);

  const reason = await form.show();
  try {
    system.clearRun(intervalId);
  } catch {}
  if (reason === DataDrivenScreenClosedReason.UserBusy) {
    return system.run(() => showScoreboardHub(player, ctx));
  }
  if (pendingNav) return system.run(pendingNav);
  if (saved) return; // committed → exit cleanly without the discard prompt
  // Engine close (bottom Close / corner ✕) or escape with unsaved edits →
  // confirm. Keep editing reopens with the in-progress config; Discard dismisses
  // to game.
  if (snapshot() !== initial) {
    ctx.cfg = buildCfg();
    ctx.pos = { x: xObs.getData(), y: yObs.getData(), z: zObs.getData() };
    return system.run(async () => {
      if (await confirmDiscardChanges(player))
        return showScoreboardHub(player, ctx);
    });
  }
}

export async function showScoreboardCreate(player, blockLocation, cfg, pos) {
  if (!pos) {
    pos = {
      x: blockLocation.x + 0.5,
      y: blockLocation.y + 1,
      z: blockLocation.z + 0.5,
    };
  }
  const ctx = {
    mode: "create",
    blockLocation,
    cfg: { ...defaultScoreboardCfg(), ...(cfg || {}) },
    pos,
  };
  return showScoreboardHub(player, ctx);
}

async function showScoreboardEdit(player, entity, cfg) {
  const loc = entity.location;
  const ctx = {
    mode: "edit",
    entity,
    cfg: { ...defaultScoreboardCfg(), ...(cfg || {}) },
    pos: { x: loc.x, y: loc.y, z: loc.z },
  };
  return showScoreboardHub(player, ctx);
}

// =========================================================
// Restore missing holograms (admin only)
// =========================================================

export async function showHologramRestore(player) {
  if (!isAdmin(player).ok) return;
  const missing = scanMissingHolograms();
  if (!missing.length) {
    tell(player, t("jm_at.holo.restore_all_present"));
    return;
  }

  const form = new ActionFormData()
    .title(t("jm_at.holo.restore_title"))
    .body(t("jm_at.holo.restore_body", missing.length))
    .button(t("jm_at.holo.btn_restore_all", missing.length));

  for (const entry of missing) {
    // Hologram line content is user-authored \u2014 shown raw, never keyed.
    const preview = entry.lines[0]
      ? entry.lines[0].length > 25
        ? entry.lines[0].slice(0, 25) + "\u2026"
        : entry.lines[0]
      : t("jm_at.holo.restore_empty_preview");
    const dim = (entry.dimId ?? "").replace("minecraft:", "");
    form.button(
      raw(
        preview,
        `\n\u00a78${dim} ${Math.round(entry.pos.x)}, ${Math.round(entry.pos.y)}, ${Math.round(entry.pos.z)}`,
      ),
    );
  }
  form.button(t("jm_at.common.btn_back_bold"));
  form.button(CLOSE_BTN_LABEL, CLOSE_BTN_ICON);

  const res = await form.show(player);
  // Invoked as a standalone dialog from control panel; X exits the flow
  if (res.canceled) return;

  if (res.selection === 0) {
    // Restore all
    let restored = 0;
    for (const entry of missing) {
      try {
        restoreHologram(entry);
        restored++;
      } catch {}
    }
    tell(player, t("jm_at.holo.restore_done", restored, missing.length));
    return;
  }

  const entryIdx = res.selection - 1;
  if (entryIdx >= 0 && entryIdx < missing.length) {
    try {
      restoreHologram(missing[entryIdx]);
      tell(player, t("jm_at.holo.restore_one"));
    } catch {
      return warnForm(player, t("jm_at.holo.restore_failed"), () =>
        showHologramRestore(player),
      );
    }
    return showHologramRestore(player);
  }
  // Back (missing.length + 1) or Close (missing.length + 2) — just return
}
