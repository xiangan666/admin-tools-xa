export async function showHologramCreate(player, blockLocation, lines, pos) {
  const at = pos || {
    x: blockLocation.x + 0.5,
    y: blockLocation.y + 1,
    z: blockLocation.z + 0.5,
  };
  // First entry: let the player choose the hologram type.
  if (lines === undefined) {
    const choice = await new ActionFormData()
      .title(t("jm_at.holo.create_title"))
      .body(t("jm_at.holo.create_body"))
      .button(t("jm_at.holo.btn_type_text"))
      .button(t("jm_at.holo.btn_type_scoreboard"))
      .button(t("jm_at.holo.btn_type_stat"))
      .show(player);
    if (choice.canceled) return;
    if (choice.selection === 1) {
      return system.run(() =>
        showScoreboardCreate(player, blockLocation, null, at),
      );
    }
    if (choice.selection === 2) {
      return system.run(() =>
        showStatLeaderboardPicker(player, blockLocation, at),
      );
    }
    lines = [""];
  }
  return showHologramTextEditor(player, {
    mode: "create",
    blockLocation,
    lines: lines && lines.length ? lines : [""],
    pos: at,
  });
}

/**
 * Picker for the "Stat Leaderboard" hologram type. Lists the stats the addon
 * already tracks (playtime, kills, deaths, block stats). Choosing one creates
 * (or reuses) its backing scoreboard objective, seeds it from everyone online so
 * the preview isn't empty, then hands off to the normal scoreboard hub
 * pre-filled with that objective — so it's a standard scoreboard hologram from
 * there on (live refresh, edit, restore all work unchanged).
 */
async function showStatLeaderboardPicker(player, blockLocation, pos) {
  const form = new ActionFormData()
    .title(t("jm_at.holo.stat_picker_title"))
    .body(t("jm_at.holo.stat_picker_body"));
  // Picker buttons display translated; stat.label (the stored objective
  // display name / hologram title) stays a plain string.
  for (const stat of TRACKED_STATS) form.button(t(stat.labelKey));
  form.button(t("jm_at.common.btn_back_bold"));
  form.button(CLOSE_BTN_LABEL, CLOSE_BTN_ICON);

  const res = await form.show(player);
  if (res.canceled) return; // X = back out of the flow
  const backIdx = TRACKED_STATS.length;
  const closeIdx = TRACKED_STATS.length + 1;
  if (res.selection === closeIdx) return;
  if (res.selection === backIdx) {
    // Back → re-open the hologram-type chooser at the same spot.
    return system.run(() =>
      showHologramCreate(player, blockLocation, undefined, pos),
    );
  }
  const stat = TRACKED_STATS[res.selection];
  if (!stat) return;
  // Materialize + seed the objective before opening the hub so its live preview
  // shows real entries immediately.
  ensureStatObjective(stat);
  return system.run(() =>
    showScoreboardCreate(
      player,
      blockLocation,
      {
        objective: stat.objId,
        title: stat.label,
        commaScores: true,
        timeFormat: stat.timeFormat ?? "",
      },
      pos,
    ),
  );
}

export async function showHologramEdit(player, entity, lines, pos) {
  if (!lines) {
    const data = getHologramData(entity);
    if (!data) {
      tell(player, t("jm_at.holo.err_read_data"));
      return;
    }
    if (data.scoreboard) {
      return showScoreboardEdit(player, entity, data.scoreboard);
    }
    lines = data.lines;
  }
  const loc = entity.location;
  return showHologramTextEditor(player, {
    mode: "edit",
    entity,
    lines: lines && lines.length ? lines : [""],
    pos: pos || { x: loc.x, y: loc.y, z: loc.z },
  });
}

/**
 * DDUI (CustomForm) editor for text holograms, shared by create and edit. Each
 * line is a text field (type & color codes; § works too) and the preview label
 * re-renders live. Lines reveal one at a time via "Add line"; position is
 * inline. spawnHologram/updateHologram stay the authority.
 * ctx = { mode, blockLocation?, entity?, lines[], pos }.
 */
async function showHologramTextEditor(player, ctx) {
  const max = LIMITS.HOLOGRAM_LINE_MAX;
  const initLines = (ctx.lines && ctx.lines.length ? ctx.lines : [""]).map(
    toAmpCodes,
  );
  let shownCount = Math.max(
    1,
    initLines.filter((l) => l.trim().length > 0).length,
  );

  const lineObs = [];
  const lineVisible = [];
  for (let i = 0; i < max; i++) {
    lineObs.push(
      new ObservableString(initLines[i] ?? "", { clientWritable: true }),
    );
    lineVisible.push(new ObservableBoolean(i < shownCount));
  }
  const canAddLine = new ObservableBoolean(shownCount < max);

  const xObs = new ObservableString(String(ctx.pos.x), {
    clientWritable: true,
  });
  const yObs = new ObservableString(String(ctx.pos.y), {
    clientWritable: true,
  });
  const zObs = new ObservableString(String(ctx.pos.z), {
    clientWritable: true,
  });

  const preview = new ObservableString("");
  const status = new ObservableString("");
  const statusShown = new ObservableBoolean(false);

  const currentLines = () => lineObs.map((o) => o.getData());
  const refresh = () => {
    const filled = currentLines()
      .map((l) => applyColorCodes(String(l)))
      .filter((l) => l.length > 0);
    preview.setData(
      filled.length ? filled.map((l) => l + "§r").join("\n") : "§7尚未设置文本行",
    );
    status.setData("");
    statusShown.setData(false);
  };
  refresh();
  for (const o of lineObs) o.subscribe(refresh);

  // Dirty-check: closing with unsaved edits prompts before discarding.
  const snapshot = () =>
    JSON.stringify([
      ...lineObs.map((o) => o.getData()),
      xObs.getData(),
      yObs.getData(),
      zObs.getData(),
    ]);
  const initial = snapshot();
  let pendingNav = null; // Remove → confirm dialog after the form closes
  let saved = false; // commit succeeded → skip the discard prompt on close

  const form = new CustomForm(
    player,
    ctx.mode === "edit"
      ? t("jm_at.holo.edit_title")
      : t("jm_at.holo.create_title"),
  );
  form.header(t("jm_at.holo.header_preview"));
  form.spacer();
  form.label(preview);
  form.spacer();
  form.divider();
  form.label(t("jm_at.holo.tip_color_codes"));
  form.spacer();
  for (let i = 0; i < max; i++) {
    form.textField(
      i === 0
        ? t("jm_at.holo.field_line1")
        : t("jm_at.holo.field_line_n", i + 1),
      lineObs[i],
      { visible: lineVisible[i] },
    );
  }
  form.spacer({ visible: canAddLine });
  form.button(
    t("jm_at.holo.btn_add_line"),
    () => {
      if (shownCount >= max) return;
      lineVisible[shownCount].setData(true);
      shownCount++;
      canAddLine.setData(shownCount < max);
    },
    { visible: canAddLine },
  );
  form.divider();
  form.spacer();
  form.label(t("jm_at.holo.label_position"));
  form.spacer();
  form.textField(t("jm_at.holo.field_x"), xObs);
  form.textField(t("jm_at.holo.field_y"), yObs);
  form.textField(t("jm_at.holo.field_z"), zObs);
  form.spacer();
  form.label(status, { visible: statusShown });
  form.spacer({ visible: statusShown });

  const commit = () => {
    const cleaned = currentLines()
      .map((l) => applyColorCodes(String(l)).slice(0, LIMITS.HOLOGRAM_LINE_LEN))
      .filter((l) => l.length > 0);
    if (!cleaned.length) {
      status.setData("§c请先输入至少一行文本。");
      statusShown.setData(true);
      return;
    }
    const x = parseFloat(xObs.getData());
    const y = parseFloat(yObs.getData());
    const z = parseFloat(zObs.getData());
    if (isNaN(x) || isNaN(y) || isNaN(z)) {
      status.setData("§c坐标无效，请只输入数字。");
      statusShown.setData(true);
      return;
    }
    if (ctx.mode === "edit") {
      updateHologram(ctx.entity, cleaned, { x, y, z }, undefined);
      tell(player, t("jm_at.holo.updated"));
    } else {
      if (getHologramRegistry().length >= LIMITS.HOLOGRAM_REGISTRY_MAX) {
        status.setData(
          `§c全息图数量已达上限（${LIMITS.HOLOGRAM_REGISTRY_MAX}），请先删除一个。`,
        );
        statusShown.setData(true);
        return;
      }
      const placed = spawnHologram(player, cleaned, { x, y, z }, null);
      if (!placed) {
        status.setData(
          "§c无法保存全息图：存储空间已满。请删除全息图或其他数据后重试。",
        );
        statusShown.setData(true);
        return;
      }
      tell(player, t("jm_at.holo.placed"));
    }
    saved = true;
    try {
      form.close();
    } catch {}
  };

  form.button(
    ctx.mode === "edit"
      ? t("jm_at.holo.btn_save_changes")
      : t("jm_at.holo.btn_place"),
    commit,
  );
  if (ctx.mode === "edit") {
    form.button(t("jm_at.holo.btn_remove"), () => {
      pendingNav = () => showRemoveConfirm(player, ctx.entity);
      try {
        form.close();
      } catch {}
    });
  }
  const reason = await form.show();
  if (reason === DataDrivenScreenClosedReason.UserBusy) {
    return system.run(() => showHologramTextEditor(player, ctx));
  }
  if (pendingNav) return system.run(pendingNav);
  if (saved) return; // committed → exit cleanly without the discard prompt
  // Engine close (bottom Close / corner ✕) or escape with unsaved edits →
  // confirm. Keep editing reopens with the in-progress text and position;
  // Discard dismisses to game. The editor is opened from a block/tool (no parent
  // menu), so Save and Discard both end up back in the world.
  if (snapshot() !== initial) {
    ctx.lines = currentLines();
    ctx.pos = { x: xObs.getData(), y: yObs.getData(), z: zObs.getData() };
    return system.run(async () => {
      if (await confirmDiscardChanges(player))
        return showHologramTextEditor(player, ctx);
    });
  }
}

// =========================================================
// Remove confirmation
// =========================================================

async function showRemoveConfirm(player, entity) {
  const form = new MessageFormData()
    .title(t("jm_at.holo.remove_title"))
    .body(t("jm_at.holo.remove_body"))
    .button1(t("jm_at.holo.btn_cancel_plain"))
    .button2(t("jm_at.holo.btn_remove_confirm"));

  const res = await form.show(player);
  if (res.canceled) return;

  // button1 = selection 0 (Cancel), button2 = selection 1 (Remove)
  if (res.selection === 1) {
    removeHologram(entity);
    tell(player, t("jm_at.holo.removed"));
  }
}

